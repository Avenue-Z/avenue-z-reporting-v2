// Turns a Peec pull into the numbers the page shows and Glean writes from (spec §5a, §7; v1.1 §4, §9, §10).
// It writes schema version 2: structured notes, each own domain on its own, the project status and the settings used.
import { DECISIONS, IMPLAUSIBLE_VISIBILITY_PCT, SENTENCES_VERSION } from './config'
import { chartedBrands } from './charted'
import type { Note, NoteKind, StoredNote } from './notes'
import type { PeecPull } from './pull'

/** The three DECISIONS this file reads; a parameter so tests can cover both settings of each. */
export type MetricDecisions = Pick<typeof DECISIONS, 'rankAmong' | 'competitorSiteGaps' | 'sourceMixWeight'>

/** The settings a generation used. Stored with the data so a later settings change never alters the row (v1.1 §8). */
export interface SettingsUsed {
  rankAmong: number | null
  peecOpportunityRows: number
  methodologyStatesPromptsAndModels: boolean
  fixedNextStep: string | null
}
/** What a row from before v1.1 was generated with. Literal on purpose: a later config.ts edit must never change how a version 1 row reads. */
export const V1_SETTINGS_USED: SettingsUsed = Object.freeze({
  rankAmong: null,
  peecOpportunityRows: 1,
  methodologyStatesPromptsAndModels: true,
  fixedNextStep: null,
})
export const settingsUsedOf = (d: { settingsUsed?: SettingsUsed }): SettingsUsed => d.settingsUsed ?? V1_SETTINGS_USED

export interface BrandMetric { id: string; name: string; isOwn: boolean; visibilityPct: number; sovPct: number | null; position: number | null; rank: number }
export interface Kpi { label: string; value: string }
export interface SourceSlice { label: string; weight: number; pct: number }
export interface OwnSite { domain: string; retrievedChats: number; retrievedPct: number | null }
export interface SnapshotData {
  /** 2 for rows generated by v1.1. Absent on version 1 rows, which keep their version 1 Data block and notes. */
  schemaVersion?: 2
  projectId: string
  projectName: string
  brand: string
  generatedAt: string
  window: { start: string; end: string }
  windowLabel: string
  category: string | null
  market: string | null
  brands: BrandMetric[]
  own: BrandMetric
  kpis: Kpi[]
  competitorsTracked: number
  /** The size of the ranked set: the n in "#i of n brands". */
  rankN: number
  leaderGaps: { name: string; visibilityPoints: number; sovPoints: number | null }[]
  ownDomains: string[]
  /** Every own domain's retrieved chats added up. Never paired with one domain's percentage. */
  ownRetrievedChats: number
  /** The own site's percentage when exactly one own domain has retrievals (version 2), else null. */
  ownRetrievedPct: number | null
  /** Round 3 (pillars D3 (a)): the source-mix weight of the brand's own rows (OWN class or own-domain match, weight above
   *  0), the Content pillar's share. Absent on older rows, which are never pillar rows. */
  ownMixWeight?: number
  /** Paul, #415 review: the same own rows' weight by the source type Peec files them under (the donut's labels), so a
   *  pillar line takes the brand's own site out of the Editorial and Competitor shares. Absent on older rows. */
  ownMixByType?: Record<string, number>
  sourceMix: SourceSlice[]
  gapDomains: { domain: string; retrievedChats: number }[]
  actions: { title: string; impact: string; type: string }[]
  promptCount: number | null
  models: string[]
  /** Version 1 rows hold strings; version 2 rows hold Note objects. */
  notes: StoredNote[]
  /** Version 2: Peec's project status (PITCH or PITCH_ENDED). */
  projectStatus?: string
  /** Version 2: each own domain with retrievals, most retrieved first. */
  ownSites?: OwnSite[]
  /** Version 2: the settings this generation used. */
  settingsUsed?: SettingsUsed
  /** Spec v1.1 §19.5: the SENTENCES_VERSION of rows whose context, findings and methodology code wrote (sentences.ts). The
   *  pillar lines are not versioned: a pillar row is told apart by its marker (Paul, #415 review). Absent on older rows,
   *  whose Glean text and grounding stay exactly as they were. */
  sentences?: number
  /** Spec v1.1 §19.5: 1 plus the domains with more retrieved chats than the most retrieved own site; null when none. */
  ownSiteRank?: number | null
  /** Spec v1.1 §19.5: the ranked roster brands with no Peec row (zero visibility), in rank order. */
  noDataBrands?: string[]
  /** 2026-10-19 Peec parity: the source-mix weighting this row was generated with. Absent on older rows, which weighted
   *  by retrieval_count; prompt.ts keeps their Data line as it was. */
  sourceMixWeight?: MetricDecisions['sourceMixWeight']
}

/** Python's round(x, dp): correctly rounded from the exact binary value, ties to even (symmetric for negatives). */
export function pyRound(x: number, dp: number): number {
  if (x < 0) return -pyRound(-x, dp)
  const exact = x.toFixed(100)
  const [int, frac = ''] = exact.split('.')
  const tail = frac.slice(dp)
  if (/^50*$/.test(tail)) {
    const kept = frac.slice(0, dp)
    const last = Number((kept || int).slice(-1))
    const down = Number(dp ? `${int}.${kept}` : int)
    return last % 2 === 0 ? down : Number((down + 10 ** -dp).toFixed(dp))
  }
  return Number(x.toFixed(dp))
}

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
/** 'YYYY-MM-DD' (a UTC calendar day from Peec) to 'Oct 1, 2026'. */
export function fmtDay(iso: string): string {
  const [y, m, d] = iso.slice(0, 10).split('-').map(Number)
  return `${MONTHS[m - 1]} ${d}, ${y}`
}

/** The US Eastern calendar day of an instant as 'YYYY-MM-DD'. */
const easternIso = (d: Date): string => new Intl.DateTimeFormat('en-CA', { timeZone: 'America/New_York', year: 'numeric', month: '2-digit', day: '2-digit' }).format(d)

/** The US Eastern calendar day of an instant, formatted like fmtDay (spec §5 row 10). */
export function fmtEasternDay(d: Date): string {
  return fmtDay(easternIso(d))
}

/** The Prepared date (spec v1.1 §19.8): the later of the Eastern day of `now` and the data window's last UTC day, so an
 *  evening pitch run whose data sits on the next UTC day never shows a window ending after the Prepared date. */
export function preparedDay(now: Date, windowEnd: string): string {
  const today = easternIso(now)
  const end = windowEnd.slice(0, 10)
  return fmtDay(end > today ? end : today)
}

const TITLE: Record<string, string> = {
  CORPORATE: 'Corporate', EDITORIAL: 'Editorial', INSTITUTIONAL: 'Institutional', OTHER: 'Other',
  REFERENCE: 'Reference', UGC: 'UGC', COMPETITOR: 'Competitor', OWN: 'You', RELATED: 'Related',
}
/** aivx agent/peec_api_transform.py:21-32: built-ins to their display form, OWN to You, custom names verbatim. */
export const titleClassification = (c: string): string => TITLE[c] ?? c

const pct1 = (ratio: number) => pyRound(ratio * 100, 1)
/** a minus b for two 1-decimal values, exact to the tenth (spec v1.1 §19.4). */
export const tenths = (a: number, b: number): number => Math.round((a - b) * 10) / 10
const bare = (d: string) => d.trim().toLowerCase().replace(/^www\./, '')

export function buildSnapshotData(
  pull: PeecPull,
  generatedAt: string,
  decisions: MetricDecisions = DECISIONS,
  used: Omit<SettingsUsed, 'rankAmong'> = V1_SETTINGS_USED,
): SnapshotData {
  if (decisions.rankAmong !== null && !(Number.isInteger(decisions.rankAmong) && decisions.rankAmong >= 2)) throw new Error('DECISIONS.rankAmong must be null or a whole number of 2 or more')
  const notes: Note[] = []
  const note = (kind: NoteKind, text: string) => { notes.push({ kind, text }) }
  // One entry per distinct brand id across the roster and the report rows. A roster brand with no row is a
  // zero-visibility entry for ranking only (spec "Competitive rank"): it is never drawn or listed.
  type Entry = { id: string; name: string; visibility: number; share_of_voice: number | null | undefined; position: number | null | undefined; hasRow: boolean; pct: number }
  const byId = new Map<string, Entry>()
  for (const b of pull.roster) byId.set(b.id, { id: b.id, name: b.name, visibility: 0, share_of_voice: null, position: null, hasRow: false, pct: 0 })
  for (const r of pull.brands) byId.set(r.brand.id, { id: r.brand.id, name: r.brand.name, visibility: r.visibility, share_of_voice: r.share_of_voice, position: r.position, hasRow: true, pct: pct1(r.visibility) })
  const entries = [...byId.values()].sort((a, b) => (b.pct - a.pct) || (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
  const totalBrands = entries.length
  // Q2: keep the brand and its rankAmong - 1 most visible competitors, in displayed-visibility order.
  const cut = decisions.rankAmong !== null && decisions.rankAmong < totalBrands
  const keptIds = new Set(entries.filter((e) => e.id !== pull.ownBrand.id).slice(0, cut ? decisions.rankAmong! - 1 : totalBrands).map((e) => e.id))
  const ranked = entries.filter((e) => e.id === pull.ownBrand.id || keptIds.has(e.id))
  const rankN = ranked.length
  const noData = entries.filter((e) => !e.hasRow).length
  const brands: BrandMetric[] = ranked.filter((e) => e.hasRow).map((e) => ({
    id: e.id,
    name: e.name,
    isOwn: e.id === pull.ownBrand.id,
    visibilityPct: e.pct,
    sovPct: typeof e.share_of_voice === 'number' ? pct1(e.share_of_voice) : null,
    position: typeof e.position === 'number' ? pyRound(e.position, 1) : null,
    rank: 1 + ranked.filter((o) => o.pct > e.pct).length,
  }))
  const own = brands.find((b) => b.isOwn)!
  const competitorsTracked = pull.roster.filter((b) => !b.is_own).length

  const kpis: Kpi[] = [{ label: 'AI visibility', value: `${own.visibilityPct.toFixed(1)}%` }]
  // v1.1 §9: with no competitors share of voice is 100% by construction, so its card is left out.
  if (own.sovPct === null) note('missing_metric', 'Peec has no share of voice for the brand in this window, so that card is left out.')
  else if (competitorsTracked === 0) note('missing_metric', 'With no competitors tracked, share of voice is 100% by construction, so that card is left out.')
  else kpis.push({ label: 'AI share of voice', value: `${own.sovPct.toFixed(1)}%` })
  if (own.position !== null) kpis.push({ label: 'Average answer position', value: `#${own.position.toFixed(1)}` })
  else note('missing_metric', 'Peec has no answer position for the brand in this window, so that card is left out.')
  if (competitorsTracked > 0) {
    kpis.push({ label: 'Competitive rank', value: `#${own.rank} of ${rankN} brands` })
    note('rank_basis', cut
      ? `Rank is by visibility among ${rankN} of the ${totalBrands} brands tracked in Peec: the brand and the competitors with the highest visibility.`
      : `Rank is by visibility among the ${rankN} brands tracked in Peec.`)
    if (noData === 1) note('no_data_brands', '1 tracked brand has no Peec data in this window and counts as zero visibility.')
    else if (noData > 1) note('no_data_brands', `${noData} tracked brands have no Peec data in this window and count as zero visibility.`)
  } else {
    note('no_competitors', 'No competitors tracked in this Peec project')
  }
  // Spec §7: a note only. Never on the page, in the Data block or in the copy, and it never blocks Approve.
  for (const b of brands) {
    if (b.visibilityPct > IMPLAUSIBLE_VISIBILITY_PCT) {
      note('high_visibility', `${b.name} shows ${b.visibilityPct.toFixed(1)}% AI visibility, which is unusually high. Check this brand's setup in Peec before sending: a name that is a common word can match unrelated answers.`)
    }
  }
  const windowLabel = pull.window.start === pull.window.end ? fmtDay(pull.window.start) : `${fmtDay(pull.window.start)} to ${fmtDay(pull.window.end)}`
  if (pull.rangePicked && (pull.requested.start !== pull.window.start || pull.requested.end !== pull.window.end)) {
    note('requested_range', `You asked for ${fmtDay(pull.requested.start)} to ${fmtDay(pull.requested.end)}. Peec has data for ${windowLabel}, so the report covers those days.`)
  }
  // 2026-10-19 (Ryan): data on the pull's own UTC day can still change in Peec, which made a report differ from the
  // dashboard. The pull's instant decides, not generatedAt, which a run crossing midnight UTC could put on the next day.
  // Paul (#403): a rerun keeps the dates (generate route), so it can warn again; leaving the day out is offered only
  // when the window has an earlier day with data, since a one-day project has nothing before it. The day is named as
  // the report's Data window names it (UTC), not as "the day it was generated".
  if (pull.window.end === pull.pulledDay) {
    const dayBefore = new Date(Date.parse(`${pull.window.end}T00:00:00Z`) - 86_400_000).toISOString().slice(0, 10)
    const leaveOut = pull.window.start < pull.window.end ? `, or, to leave that day out, start a new report that ends ${fmtDay(dayBefore)}` : ''
    note('same_day_data', `This report includes ${fmtDay(pull.window.end)}, and Peec can still update that day's data, so these numbers may change. Rerun later to pick up Peec's latest numbers${leaveOut}.`)
  }

  // Spec v1.1 §19.4 (supersedes 5a row 17 and 18.1): competitor minus own from the printed 1-decimal values, in tenths,
  // so a gap always equals the difference of the two numbers on the page, as in Ryan's example. Every brand with a
  // higher displayed visibility is listed, so the gaps agree with the rank card; a tied brand is never a leader.
  const leaderGaps = brands
    .filter((b) => b.visibilityPct > own.visibilityPct)
    .map((rival) => ({
      name: rival.name,
      visibilityPoints: tenths(rival.visibilityPct, own.visibilityPct),
      sovPoints: rival.sovPct !== null && own.sovPct !== null ? tenths(rival.sovPct, own.sovPct) : null,
    }))
  const noDataBrands = ranked.filter((e) => !e.hasRow && e.id !== pull.ownBrand.id).map((e) => e.name)

  // v1.1 §9: each own domain keeps its own count and percentage; the sum is never paired with one domain's percentage.
  const ownDomains = (pull.ownBrand.domains ?? []).map(bare)
  // A row is own when Peec classifies it OWN, or its domain is an own domain or a subdomain of one, the same
  // match the gap filter uses below (spec 18.2). An empty entry is skipped so it can never match by suffix.
  const ownMatch = ownDomains.filter(Boolean)
  const ownRows = pull.domains.filter((r) => {
    if (r.classification === 'OWN') return true
    const d = bare(r.domain)
    return ownMatch.some((od) => d === od || d.endsWith(`.${od}`))
  })
  const ownSites: OwnSite[] = ownRows
    .map((r) => ({ domain: r.domain, retrievedChats: r.retrieved_chat_count ?? 0, retrievedPct: typeof r.retrieved_percentage === 'number' ? pct1(r.retrieved_percentage) : null }))
    .sort((a, b) => (b.retrievedChats - a.retrievedChats) || (a.domain < b.domain ? -1 : 1))
  const ownRetrievedChats = ownSites.reduce((s, x) => s + x.retrievedChats, 0)
  const ownRetrievedPct = ownSites.length === 1 ? ownSites[0].retrievedPct : null
  const topOwn = ownSites[0]
  const ownSiteRank = topOwn && topOwn.retrievedChats > 0 ? 1 + pull.domains.filter((r) => (r.retrieved_chat_count ?? 0) > topOwn.retrievedChats).length : null
  if (!ownRows.length) note('own_domains', "No retrievals of the brand's own site in this window.")
  if (ownRows.length > 1) note('own_domains', `The brand has ${ownRows.length} own domains with retrievals; each is listed with its own count and percentage.`)

  const weights = new Map<string, number>()
  for (const r of pull.domains) {
    const w = r[decisions.sourceMixWeight] ?? 0
    if (w <= 0) continue
    // The contract guarantees a non-empty classification on every row (contracts.ts, peec.domains_report).
    const label = titleClassification(r.classification)
    weights.set(label, (weights.get(label) ?? 0) + w)
  }
  // Round 3 (pillars spec D3 (a)): the Content pillar counts the brand's own rows the way the own-site bullet does.
  const ownMixWeight = ownRows.reduce((s, r) => { const w = r[decisions.sourceMixWeight] ?? 0; return w > 0 ? s + w : s }, 0)
  const ownMixByType: Record<string, number> = {}
  for (const r of ownRows) {
    const w = r[decisions.sourceMixWeight] ?? 0
    if (w > 0) { const label = titleClassification(r.classification); ownMixByType[label] = (ownMixByType[label] ?? 0) + w }
  }
  const total = [...weights.values()].reduce((s, w) => s + w, 0)
  const sourceMix = [...weights.entries()]
    .sort((a, b) => (b[1] - a[1]) || (a[0] < b[0] ? -1 : 1))
    .map(([label, weight]) => ({ label, weight, pct: total ? pyRound((weight / total) * 100, 1) : 0 }))
  if (!sourceMix.length) note('empty_source_mix', 'Peec reported no source weights for this window, so the source mix is empty.')

  // Round 3 (Ryan, 2026-10-21: "Only include competitor domains"): the gaps are the own sites of the competitors the
  // bar chart shows (chartedIds, charted.ts; round 3 QA, spec 2026-10-22 F1), where the brand does not appear. A site is
  // a charted competitor's when its domain is one of that competitor's roster domains or a subdomain of one, or Peec
  // classifies it COMPETITOR and it mentions a charted competitor. The brand's own site never counts (own wins), nor does
  // a site of any other competitor: cut by rankAmong, ranked below the chart, or without a Peec row (spec 2026-10-21 E2,
  // D1, D3, D4 (a)). With no competitors tracked the report names no outside brand, so it lists none.
  const chartedIds = new Set(chartedBrands(brands).filter((b) => !b.isOwn).map((b) => b.id))
  const rosterSites = (keep: (id: string) => boolean) => pull.roster.filter((b) => keep(b.id)).flatMap((b) => (b.domains ?? []).map(bare)).filter(Boolean)
  const keptSites = rosterSites((id) => chartedIds.has(id))
  const cutSites = rosterSites((id) => id !== pull.ownBrand.id && !chartedIds.has(id))
  const within = (d: string, sites: string[]) => sites.some((s) => d === s || d.endsWith(`.${s}`))
  /** The length of the closest (longest) site the domain is or sits under; -1 when none. */
  const closest = (d: string, sites: string[]) => sites.reduce((n, s) => (d === s || d.endsWith(`.${s}`) ? Math.max(n, s.length) : n), -1)
  const gapDomains = !decisions.competitorSiteGaps || competitorsTracked === 0 ? [] : pull.domains
    .filter((r) => {
      // A domain no answer retrieved is not a gap worth naming (final review M3).
      if ((r.retrieved_chat_count ?? 0) <= 0) return false
      const d = bare(r.domain)
      if (r.classification === 'OWN' || within(d, ownMatch)) return false
      // The closest roster domain decides whose site it is, so a cut competitor's parent domain never hides a kept
      // competitor's subdomain; a domain on both rosters stays cut (Paul, #413 review).
      const kept = closest(d, keptSites)
      const cut = closest(d, cutSites)
      if (cut >= 0 && cut >= kept) return false
      const ids = new Set(r.mentioned_brands.map((m) => m.id))
      if (ids.has(pull.ownBrand.id)) return false
      return kept >= 0 || (r.classification === 'COMPETITOR' && [...ids].some((id) => chartedIds.has(id)))
    })
    .sort((a, b) => ((b.retrieved_chat_count ?? 0) - (a.retrieved_chat_count ?? 0)) || (a.domain < b.domain ? -1 : 1))
    .slice(0, 4)
    .map((r) => ({ domain: r.domain, retrievedChats: r.retrieved_chat_count ?? 0 }))

  if (!pull.profile) note('no_profile', 'Peec has no project profile, so category and market need validation.')
  for (const w of pull.warnings) note('peec_warning', w)
  note('project', `Peec project ${pull.project.id} (${pull.project.status}). Window ${pull.window.start} to ${pull.window.end}, all models: ${pull.models.join(', ') || 'none reported'}.`)

  return {
    schemaVersion: 2,
    projectId: pull.project.id,
    projectName: pull.project.name,
    brand: pull.ownBrand.name,
    generatedAt,
    window: pull.window,
    windowLabel,
    category: pull.profile?.industry ?? null,
    market: pull.profile?.markets.length ? pull.profile.markets.join(', ') : null,
    brands,
    own,
    kpis,
    competitorsTracked,
    rankN,
    leaderGaps,
    ownDomains,
    ownRetrievedChats,
    ownRetrievedPct,
    ownMixWeight,
    ownMixByType,
    sourceMix,
    sourceMixWeight: decisions.sourceMixWeight,
    gapDomains,
    // Round 3 (Paul, #415 review): the pull no longer reads Peec's actions. Older rows keep the ones they stored.
    actions: [],
    promptCount: pull.promptCount,
    models: pull.models,
    notes,
    projectStatus: pull.project.status,
    ownSites,
    settingsUsed: { rankAmong: decisions.rankAmong, peecOpportunityRows: used.peecOpportunityRows, methodologyStatesPromptsAndModels: used.methodologyStatesPromptsAndModels, fixedNextStep: used.fixedNextStep },
    sentences: SENTENCES_VERSION,
    ownSiteRank,
    noDataBrands,
  }
}

/** 'Oct 2, 2026, 11:00 AM' in US Eastern, for the hub and the open list (spec v1.1 §5, §6). */
export function fmtEasternDateTime(d: Date): string {
  const time = new Intl.DateTimeFormat('en-US', { timeZone: 'America/New_York', hour: 'numeric', minute: '2-digit' }).format(d).replace(/\u202f/g, ' ')
  return `${fmtEasternDay(d)}, ${time}`
}
